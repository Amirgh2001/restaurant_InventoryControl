#!/usr/bin/env bash
# اسکریپت راه‌اندازی سریع سامانه مدیریت موجودی رستوران
set -e

PORT=${1:-8080}
PYTHON_BIN="/usr/local/bin/python3"

if ! command -v "$PYTHON_BIN" &> /dev/null; then
    PYTHON_BIN="python3"
fi

echo "=========================================================="
echo " 🍽️  سامانه مدیریت موجودی و انبارداری رستوران (نسخه کامل)  "
echo "=========================================================="
echo "در حال بررسی و مقداردهی اولیه پایگاه داده..."

$PYTHON_BIN app/database.py

echo "پایگاه داده آماده است."
echo "در حال اجرای سرور روی پورت $PORT..."
echo "🔗 آدرس سامانه در مرورگر: http://localhost:$PORT"
echo "=========================================================="
echo "کاربران پیش‌فرض جهت ورود:"
echo " - مدیر مجموعه: نام کاربری admin / رمز admin123"
echo " - سرپرست شیفت: نام کاربری supervisor / رمز sup123"
echo " - اپراتور: نام کاربری operator / رمز op123"
echo " - انبارگردان: نام کاربری auditor / رمز audit123"
echo " - مدیر سیستم: نام کاربری sysadmin / رمز sys123"
echo "=========================================================="

exec $PYTHON_BIN app/server.py "$PORT"
